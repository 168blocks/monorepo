package dev.vxcc.alexs168.pgecs.lambdafuzz

import java.io.File
import kotlin.random.Random

/**
 * Writes random query predicates over `FuzzRec` (libs/pgecs/src/test/.../lambda/LambdaDifferentialTest.kt)
 * as Kotlin source, for the test source set: `Generate <out dir> <seed> <count>`.
 *
 * The predicates only use what the lambda decompiler and lowering translate, and are total on every
 * record (no `!!` on null, no division by a possible zero, `getOrNull` instead of `get`), so the
 * Kotlin result is always defined and the engine must agree with it.
 */
fun main(args: Array<String>) {
    val (out, seed, count) = args
    val gen = LambdaGen(Random(seed.toLong()))
    val lambdas = List(count.toInt()) { gen.lambda() }
    val dir = File(out, "dev/vxcc/alexs168/pgecs/lambda")
    dir.deleteRecursively()
    dir.mkdirs()
    val chunks = lambdas.chunked(CHUNK)
    val header = buildString {
        appendLine("// Generated by :libs:pgecs:generateLambdaFuzz (seed $seed). Do not edit.")
        appendLine("@file:Suppress(\"ConvertTwoComparisonsToRangeCheck\", \"SimplifyBooleanWithConstants\", \"KotlinConstantConditions\", \"UNUSED_VARIABLE\", \"ReplaceSizeCheckWithIsNotEmpty\", \"ReplaceSizeZeroCheckWithIsEmpty\", \"DUPLICATE_LABEL_IN_WHEN\")")
        appendLine("package dev.vxcc.alexs168.pgecs.lambda")
        appendLine()
        appendLine("import java.time.Instant")
        appendLine()
    }
    File(dir, "GeneratedLambdas.kt").writeText(
        header + "object GeneratedLambdas {\n" +
            "    const val SEED = ${seed}L\n" +
            "    val all: List<GeneratedLambda> by lazy { ${chunks.indices.joinToString(" + ") { "chunk$it()" }.ifEmpty { "emptyList()" }} }\n" +
            "}\n",
    )
    // one file per chunk: each file's class has one \$deserializeLambda\$ method for all its lambdas
    chunks.forEachIndexed { ci, chunk ->
        File(dir, "GeneratedLambdas$ci.kt").writeText(
            buildString {
                append(header)
                appendLine("internal fun chunk$ci(): List<GeneratedLambda> {")
                appendLine("    val out = ArrayList<GeneratedLambda>()")
                chunk.forEachIndexed { i, l ->
                    val n = ci * CHUNK + i
                    appendLine("    run {")
                    for (c in l.captures) appendLine("        val ${c.first} = ${c.second}")
                    appendLine("        out += GeneratedLambda($n, ${quote(l.text)}, QueryPredicate<FuzzRec> { ${l.body} })")
                    appendLine("    }")
                }
                appendLine("    return out")
                appendLine("}")
            },
        )
    }
}

private const val CHUNK = 25

/** A Kotlin string literal of [s] (which is itself Kotlin source, ASCII with `\u` escapes). */
private fun quote(s: String): String =
    "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

class Generated(val captures: List<Pair<String, String>>, val body: String) {
    val text: String get() = (captures.map { "val ${it.first} = ${it.second}; " }.joinToString("") + "{ $body }")
}

class LambdaGen(private val r: Random) {
    private val captures = ArrayList<Pair<String, String>>()

    fun lambda(): Generated {
        captures.clear()
        val body = bool(3)
        return Generated(captures.toList(), body)
    }

    private fun <T> pick(vararg xs: T): T = xs[r.nextInt(xs.size)]

    private fun capture(value: String): String {
        val name = "c${captures.size}"
        captures += name to value
        return name
    }

    // ---- literals: values that tell Kotlin and SQL apart (case outside ASCII, ß, final sigma, non-BMP).
    // Not U+E000..U+FFFF (fullwidth forms, private use): Kotlin orders strings by UTF-16 code units, so
    // those sort after a non-BMP character, while PostgreSQL's "C" collation orders by code point.

    private val strs = listOf(
        "\"ann\"", "\"Ann\"", "\"ANN\"", "\"b\"", "\"bob\"", "\"\"", "\" ann \"", "\"a\\tb\"", "\"\\u00c4rger\"",
        "\"stra\\u00dfe\"", "\"\\u00e9x\"", "\"\\ud83d\\ude00\"", "\"\\u03a3\\u0391\\u03a3\"", "\"x\"", "\"a\"", "\"n\"",
    )
    private val tags = listOf("\"red\"", "\"green\"", "\"blue\"", "\"\"")
    private val tiers = listOf("FuzzTier.GOLD", "FuzzTier.SILVER", "FuzzTier.BRONZE")
    // patterns that mean the same in java.util.regex and PostgreSQL (not \\s: PostgreSQL's includes NBSP)
    private val patterns = listOf("^a", "b$", "[0-9]", "^.{2,4}$", "nn", "^[A-Z]", "[ \\t]")

    private fun strLit() = strs[r.nextInt(strs.size)]
    // Kotlin's Int and Long arithmetic wraps around, SQL's bigint does not (and raises an error on
    // overflow): a known difference, kept out by using the extremes only in comparisons.
    private fun intLit() = pick("0", "1", "2", "3", "5", "7", "-1", "-4", "10", "100")
    private fun edgeInt() = pick("2147483647", "-2147483648", "it.huge", "0")
    private fun smallInt() = pick("1", "2", "3", "5", "7", "-1", "-3", "10")
    private fun longLit() = pick("0L", "1L", "3L", "-2L", "10L", "5000000000L")

    // ---- typed generators

    fun bool(d: Int): String {
        if (d <= 0 || r.nextInt(4) == 0) return boolLeaf(d)
        return when (r.nextInt(9)) {
            0, 1 -> "(${bool(d - 1)} && ${bool(d - 1)})"
            2, 3 -> "(${bool(d - 1)} || ${bool(d - 1)})"
            4 -> "!(${bool(d - 1)})"
            5 -> "(if (${bool(d - 1)}) ${bool(d - 1)} else ${bool(d - 1)})"
            6 -> "(when (${int(d - 1)}) { ${intLit()}, ${intLit()} -> ${bool(d - 1)}; ${intLit()} -> ${bool(d - 1)}; else -> ${bool(d - 1)} })"
            7 -> "(when { ${bool(d - 1)} -> ${bool(d - 1)}; ${bool(d - 1)} -> ${bool(d - 1)}; else -> ${bool(d - 1)} })"
            else -> "(when (it.tier) { ${tiers[0]} -> ${bool(d - 1)}; ${tiers[1]} -> ${bool(d - 1)}; else -> ${bool(d - 1)} })"
        }
    }

    private fun cmp() = pick("==", "!=", "<", "<=", ">", ">=")

    private fun boolLeaf(d: Int): String {
        val e = maxOf(d - 1, 0)
        return when (r.nextInt(26)) {
            0 -> "it.flag"
            1 -> "(it.opt == ${pick("true", "false", "null")})"
            2, 3 -> "(${int(e)} ${cmp()} ${int(e)})"
            4 -> "(${int(e)} ${cmp()} ${edgeInt()})"
            5 -> "(${long(e)} ${cmp()} ${long(e)})"
            6, 7 -> "(${str(e)} ${cmp()} ${str(e)})"
            8 -> "${str(e)}.${pick("startsWith", "endsWith", "contains")}(${str(e)})"
            9 -> "${str(e)}.${pick("isEmpty", "isNotEmpty")}()"
            10 -> "(it.alt ${pick("==", "!=")} null)"
            // not with another field: after `it.alt == null`, `it.alt == it.name` smart-casts it.name to Nothing
            11 -> "(it.alt ${pick("==", "!=")} ${if (r.nextBoolean()) strLit() else capture(strLit())})"
            12 -> "(it.m ${pick("==", "!=")} ${pick("null", int(e))})"
            13 -> "(${str(e)} ${pick("in", "!in")} listOf(${List(1 + r.nextInt(3)) { strLit() }.joinToString(", ")}))"
            14 -> "(${int(e)} ${pick("in", "!in")} ${capture("setOf<Int>(${List(r.nextInt(4)) { intLit() }.joinToString(", ")})")})"
            15 -> "(${pick(*tags.toTypedArray())} ${pick("in", "!in")} it.tags)"
            16 -> "it.tags.${pick("isEmpty", "isNotEmpty")}()"
            17 -> "(it.tags.${pick("firstOrNull()", "lastOrNull()", "getOrNull(1)")} ${pick("==", "!=")} ${pick(*tags.toTypedArray(), "null")})"
            18 -> "(${long(e)} ${pick("in", "!in")} it.nums)"
            19 -> "(it.nums.${pick("firstOrNull()", "lastOrNull()")} ${pick("==", "!=")} ${pick(longLit(), "null")})"
            20 -> "(it.tier ${pick("==", "!=")} ${pick(*tiers.toTypedArray())})"
            21 -> "(it.tier ${pick("in", "!in")} ${if (r.nextBoolean()) "listOf(${tiers.shuffled(r).take(1 + r.nextInt(2)).joinToString(", ")})" else capture("listOf(${tiers.shuffled(r).take(1 + r.nextInt(2)).joinToString(", ")})")})"
            22 -> "Regex(\"${patterns[r.nextInt(patterns.size)]}\"${pick("", ", RegexOption.IGNORE_CASE")}).${pick("containsMatchIn", "matches")}(${str(e)})"
            23 -> when (r.nextInt(3)) {
                0 -> "(it.at ${pick("==", "!=")} null)"
                1 -> "(it.at != null && it.at ${cmp()} ${capture(instantLit())})"
                else -> "(it.at?.isBefore(${capture(instantLit())}) == ${pick("true", "false")})"
            }
            24 -> "(it.ratio ${cmp()} ${pick("0.5", "-1.25", "0.0", "1e10", "it.ratio * 2.0")})"
            else -> "(${str(e)}.length ${cmp()} ${int(e)})"
        }
    }

    private fun instantLit() = pick("Instant.parse(\"2001-06-01T00:00:00Z\")", "Instant.parse(\"2101-01-01T12:00:00.000001Z\")", "Instant.EPOCH")

    fun int(d: Int): String {
        if (d <= 0 || r.nextInt(3) == 0) {
            return when (r.nextInt(10)) {
                0, 1, 2 -> "it.n"
                3 -> "it.n"
                4, 5 -> intLit()
                6 -> capture(intLit())
                7 -> "${str(0)}.length"
                8 -> "it.tags.size"
                else -> "(it.m ?: ${intLit()})"
            }
        }
        return when (r.nextInt(9)) {
            0 -> "(${int(d - 1)} + ${int(d - 1)})"
            1 -> "(${int(d - 1)} - ${int(d - 1)})"
            2 -> "(${int(d - 1)} * ${int(d - 1)})"
            3 -> "(${int(d - 1)} / ${smallInt()})"
            4 -> "(${int(d - 1)} % ${smallInt()})"
            5 -> "(-(${int(d - 1)}))"
            6 -> "(if (${bool(d - 1)}) ${int(d - 1)} else ${int(d - 1)})"
            7 -> "(when (it.tier) { ${tiers[0]} -> ${int(d - 1)}; ${tiers[2]} -> ${int(d - 1)}; else -> ${int(d - 1)} })"
            else -> "(it.m ?: ${int(d - 1)})"
        }
    }

    fun long(d: Int): String {
        if (d <= 0 || r.nextInt(3) == 0) {
            return when (r.nextInt(6)) {
                0, 1 -> "it.big"
                2 -> longLit()
                3 -> "${int(0)}.toLong()"
                4 -> "(it.nums.${pick("firstOrNull()", "lastOrNull()")} ?: ${longLit()})"
                else -> "it.nums.size.toLong()"
            }
        }
        return when (r.nextInt(3)) {
            0 -> "(${long(d - 1)} + ${long(d - 1)})"
            1 -> "(${long(d - 1)} - ${long(d - 1)})"
            else -> "${int(d - 1)}.toLong()"
        }
    }

    fun str(d: Int): String {
        if (d <= 0 || r.nextInt(3) == 0) {
            return when (r.nextInt(6)) {
                0, 1 -> "it.name"
                2 -> strLit()
                3 -> capture(strLit())
                4 -> "(it.alt ?: ${strLit()})"
                else -> "it.name"
            }
        }
        return when (r.nextInt(7)) {
            0 -> "${str(d - 1)}.${pick("lowercase", "uppercase", "trim")}()"
            1 -> "\"\${${str(d - 1)}}-\${${str(d - 1)}}\""
            2 -> "(${str(d - 1)} + ${str(d - 1)})"
            3 -> "(if (${bool(d - 1)}) ${str(d - 1)} else ${str(d - 1)})"
            4 -> "(when (it.tier) { ${tiers[1]} -> ${str(d - 1)}; else -> ${str(d - 1)} })"
            5 -> "(it.alt ?: ${str(d - 1)})"
            else -> "(when (${pick("it.name", "(it.alt ?: ${strLit()})", "it.name.lowercase()")}) { ${strLit()}, ${strLit()} -> ${str(d - 1)}; else -> ${str(d - 1)} })"
        }
    }
}
